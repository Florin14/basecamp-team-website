const byDate = (a: Article, b: Article) => +new Date(b.date) - +new Date(a.date);

export const latestNews = (limit?: number) => [...news].sort(byDate).slice(0, limit ?? news.length);

export const featuredArticle = () => news.find((a) => a.featured) ?? latestNews(1)[0];

export const articleBySlug = (slug: string) => news.find((a) => a.slug === slug);

export const relatedArticles = (slug: string, limit = 3) =>
  latestNews().filter((a) => a.slug !== slug).slice(0, limit);

export const newsCategories = () => Array.from(new Set(news.map((a) => a.category)));
